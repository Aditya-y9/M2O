-- Core Banking Deposit Subsystem DDL
CREATE TABLE ACCOUNT_MASTER (
    ACCOUNT_ID     DECIMAL(10, 0) NOT NULL,
    CUSTOMER_ID    DECIMAL(10, 0) NOT NULL,
    ACCOUNT_TYPE   CHAR(4)        NOT NULL,
    BALANCE        DECIMAL(11, 2) NOT NULL DEFAULT 0.00,
    STATUS         CHAR(1)        NOT NULL DEFAULT 'A',
    LAST_UPDATED   TIMESTAMP      NOT NULL,
    PRIMARY KEY (ACCOUNT_ID)
);

CREATE TABLE TRANSACTION_LOG (
    TXN_ID         VARCHAR(16)    NOT NULL,
    ACCOUNT_ID     DECIMAL(10, 0) NOT NULL,
    AMOUNT         DECIMAL(9, 2)  NOT NULL,
    TXN_TYPE       CHAR(3)        NOT NULL,
    CREATED_AT     TIMESTAMP      NOT NULL,
    PRIMARY KEY (TXN_ID)
);

CREATE INDEX IX_ACC_CUST ON ACCOUNT_MASTER(CUSTOMER_ID);
CREATE INDEX IX_TXN_ACC ON TRANSACTION_LOG(ACCOUNT_ID, CREATED_AT);
